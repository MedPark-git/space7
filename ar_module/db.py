def backend_name():
    if USE_PG:
        return "PostgreSQL (%s)" % _driver
    return "SQLite (%s)" % DB_PATH


def journal_mode():
    """SQLite 저널 모드 확인용. 네트워크 볼륨에서 WAL 이 꺼졌는지 볼 때 쓴다."""
    if USE_PG:
        return None
    with connect() as conn:
        row = conn.execute("PRAGMA journal_mode").fetchone()
    return list(row.values())[0] if row else None
