_PLACEHOLDER = re.compile(r"%s")


def _adapt(sql: str) -> str:
    """PostgreSQL 자리표시자를 SQLite 용으로 바꾼다."""
    return sql if USE_PG else _PLACEHOLDER.sub("?", sql)


class Cursor:
    """psycopg 와 sqlite3 커서의 공통 껍데기. 행은 항상 dict 로 돌려준다."""

    def __init__(self, raw, dialect_pg):
        self._raw = raw
        self._pg = dialect_pg

    def execute(self, sql, params=()):
        self._raw.execute(_adapt(sql), params)
        return self

    def executemany(self, sql, seq):
        self._raw.executemany(_adapt(sql), seq)
        return self

    def fetchone(self):
        row = self._raw.fetchone()
        return dict(row) if row is not None else None

    def fetchall(self):
        return [dict(r) for r in self._raw.fetchall()]

    def __iter__(self):
        for row in self._raw.fetchall():
            yield dict(row)

    @property
    def rowcount(self):
        return self._raw.rowcount


class Connection:
    def __init__(self, raw, dialect_pg):
        self._raw = raw
        self._pg = dialect_pg

    def _cursor(self):
        if self._pg:
            if _driver == "psycopg2":
                return self._raw.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
            return self._raw.cursor(row_factory=psycopg.rows.dict_row)
        return self._raw.cursor()

    def execute(self, sql, params=()):
        return Cursor(self._cursor(), self._pg).execute(sql, params)

    def executemany(self, sql, seq):
        return Cursor(self._cursor(), self._pg).executemany(sql, seq)

    def executescript(self, script):
        cur = self._cursor()
        for statement in [s.strip() for s in script.split(";") if s.strip()]:
            cur.execute(statement)


@contextmanager
def connect():
    if USE_PG:
        if _driver == "psycopg2":
            raw = psycopg2.connect(connect_timeout=10, **PG_CONFIG)
        else:
            raw = psycopg.connect(connect_timeout=10, **PG_CONFIG)
    else:
        import sqlite3
        raw = sqlite3.connect(DB_PATH, timeout=20)
        raw.row_factory = sqlite3.Row
        # 네트워크 볼륨에서는 WAL 이 켜지지 않을 수 있다. 그래도 기동은 되어야 하므로
        # 실패를 삼키고 기본 저널 모드로 계속 간다(쓰기가 더 직렬화될 뿐이다).
        try:
            raw.execute("PRAGMA journal_mode=WAL")
        except Exception:
            pass
        raw.execute("PRAGMA busy_timeout=20000")
        raw.execute("PRAGMA foreign_keys=ON")
    try:
        yield Connection(raw, USE_PG)
        raw.commit()
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


