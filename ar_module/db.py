def data_dir() -> str:
    configured = os.environ.get("AR_DATA_DIR", "").strip()
    candidates = ([configured] if configured else []) + [
        "/app/user_data", os.path.join(os.path.dirname(__file__), "user_data")
    ]
    for candidate in candidates:
        try:
            os.makedirs(candidate, exist_ok=True)
            probe = os.path.join(candidate, ".writable")
            with open(probe, "w") as fh:
                fh.write("ok")
            os.remove(probe)
            return candidate
        except OSError:
            continue
    raise RuntimeError("쓰기 가능한 데이터 디렉터리를 찾지 못했습니다.")


