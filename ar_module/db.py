def wait_for_db(attempts=12, delay=2.5):
    """컨테이너가 DB 보다 먼저 뜨는 경우가 있어 접속될 때까지 기다린다."""
    last = None
    for i in range(attempts):
        try:
            with connect() as conn:
                conn.execute("SELECT 1")
            return
        except Exception as exc:
            last = exc
            time.sleep(delay)
    raise RuntimeError("데이터베이스에 접속하지 못했습니다: %s" % last)


def init_db():
    wait_for_db()
